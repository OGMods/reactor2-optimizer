import type {
  BuildingDefinition,
  BuildingType,
  UpgradeLevel,
} from "../solver/types";

export type BuildingId = (typeof BUILDING_TABLE)[number]["id"];

/**
 * The catalogue's three UI groups. The game itself files reactors and direct
 * producers under one `heat_producer` category and the sidebar still shows
 * them on one tab, so the split the solver needs is mapped back here rather
 * than pushed into the UI.
 */
export type BuildingCategory = "cooler" | "generator" | "heat_producer";

export function buildingCategory(type: BuildingType): BuildingCategory {
  return type === "reactor" || type === "direct_producer"
    ? "heat_producer"
    : type;
}

/**
 * The number an upgrade tier is sized by, for callers that do not know the
 * role -- the sidebar's tier list, mostly. Code that does know should read the
 * specific field, which says what the number means.
 */
export function levelValue(level: UpgradeLevel): number {
  return "cooling" in level ? level.cooling : level.heat;
}

/**
 * The upgrade index a placed building is standing at, recovered from the value
 * it was placed at.
 *
 * The inverse of `placementBaseValue`, and the same trick `effectiveAtValue`
 * plays: a placement records a value rather than a level, and a building's tier
 * values strictly increase, so the value identifies the tier exactly for
 * anything the app produced. A value the catalogue does not author -- a
 * hand-edited save -- resolves to the top tier, matching what
 * `effectiveAtValue` would rate it at rather than disagreeing with it.
 *
 * `levels` is read through `readonly UpgradeLevel[]` because
 * `BuildingDefinition` is a four-variant union: `def.levels` is a union of four
 * array types, and calling an array method on that has no single compatible
 * signature. Every variant's element is a `UpgradeLevel`, which is all
 * `levelValue` needs.
 */
export function levelIndexForValue(
  def: BuildingDefinition,
  baseValue: number,
): number {
  const levels: readonly UpgradeLevel[] = def.levels;
  const index = levels.findIndex((level) => levelValue(level) === baseValue);
  return index >= 0 ? index : levels.length - 1;
}

