/**
 * The catalog.
 *
 * The table above is `as const` so `BuildingId` can be derived from it, but
 * that also makes its element type a union of 38 literal object types. Exporting
 * it through a `readonly BuildingDefinition[]` annotation gives every consumer
 * the uniform union instead, so `find(...)` narrows on `type` rather than on
 * whichever literal shape it happened to land on. Same array, not a copy.
 */
export const BUILDINGS: readonly BuildingDefinition[] = BUILDING_TABLE;

/**
 * The same catalog keyed by id, for the handful of call sites that look a
 * building up rather than iterate.
 *
 * `BUILDINGS` stays the array because its order is the order the sidebar and
 * the HUD palette render in, and because everything that consumes the roster
 * -- `getEffectiveBuildings`, the unlock list, the solver hand-off -- walks it
 * whole. Keying the table itself would have bought a lookup this map already
 * provides, at the cost of that ordering being an implementation detail of
 * object key insertion.
 */
const BUILDING_BY_ID: Readonly<Record<string, BuildingDefinition | undefined>> =
  Object.fromEntries(BUILDINGS.map((b) => [b.id, b]));

/**
 * Every building at its top tier — the roster a headless caller wants unless it
 * is modelling a particular save.
 *
 * The retired Python reference spelled this as a module constant called
 * `UNLOCKED_UPGRADES`, and it meant one checkout's progression; it is a
 * function here because nothing in this package has a progression. The app
 * never calls it: what a *player* has unlocked is the player's, and
 * `configState` is where that lives.
 */
export function allUpgradesUnlocked(
  buildings: readonly BuildingDefinition[] = BUILDINGS,
): Record<string, number> {
  const unlocks: Record<string, number> = {};
  for (const building of buildings) {
    unlocks[building.id] = building.levels.length - 1;
  }
  return unlocks;
}

/**
 * Look a building up by id.
 *
 * Every caller arrives with a plain `string` -- a saved placement, a blueprint
 * byte, the tile the user clicked -- so the record is typed over `string` and
 * returns `undefined` for an id the catalog does not carry. That keeps the
 * miss honest at the call site, which handles it anyway, rather than hiding
 * it behind a cast asserting every string is a `BuildingId`.
 */
export function findBuilding(id: string): BuildingDefinition | undefined {
  return BUILDING_BY_ID[id];
}
